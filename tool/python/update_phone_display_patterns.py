"""Update the package's phone display templates from a Telegram snapshot."""

import argparse
import asyncio
import difflib
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
COUNTRIES = ROOT / "lib/src/constant/country_codes.g.json"
OUTPUT = ROOT / "lib/src/constant/country_phone_display_patterns.g.dart"
METHOD = "help.getCountriesList"


async def fetch(previous, lang):
    try:
        from telethon import TelegramClient
        from telethon.sessions import MemorySession
        from telethon.tl.functions.help import GetCountriesListRequest
        from telethon.tl.types.help import CountriesList, CountriesListNotModified
    except ImportError:
        raise ValueError("Install Telethon 1.45.0 in a virtual environment.") from None

    api_id = int(os.environ.get("TELEGRAM_API_ID", "0"))
    api_hash = os.environ.get("TELEGRAM_API_HASH", "")
    if api_id <= 0 or not api_hash:
        raise ValueError("Set TELEGRAM_API_ID and TELEGRAM_API_HASH.")
    previous_hash = previous["response"]["hash"] if previous else 0
    client = TelegramClient(
        MemorySession(),
        api_id,
        api_hash,
        connection_retries=0,
        request_retries=0,
        auto_reconnect=False,
        receive_updates=False,
        timeout=10,
        device_model="Desktop",
        app_version="Phone display template updater",
        lang_code=lang,
        system_lang_code=lang,
    )
    try:
        await asyncio.wait_for(client.connect(), 20)
        response = await asyncio.wait_for(
            client(GetCountriesListRequest(lang_code=lang, hash=previous_hash)),
            20,
        )
    finally:
        await client.disconnect()

    if isinstance(response, CountriesListNotModified) and previous is not None:
        return previous
    if not isinstance(response, CountriesList):
        raise ValueError(f"Unexpected Telegram response: {type(response).__name__}")
    return {
        "method": METHOD,
        "captured_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "request": {"lang_code": lang, "hash": previous_hash},
        "response": response.to_dict(),
    }


def display_patterns(snapshot, package_countries):
    response = snapshot["response"]
    if snapshot["method"] != METHOD or response["_"] != "CountriesList":
        raise ValueError("Expected a complete help.getCountriesList snapshot.")

    by_iso = {}
    for country in response["countries"]:
        codes = by_iso.setdefault(country["iso2"], {})
        for code in country["country_codes"]:
            number = code["country_code"]
            patterns = code.get("patterns") or []
            if number in codes or not re.fullmatch(r"[0-9]+", number):
                raise ValueError(f"Invalid or duplicate source code: {country['iso2']} +{number}")
            if any(not re.fullmatch(r"[0-9X ]+", pattern) for pattern in patterns):
                raise ValueError(f"Unsupported template syntax: {country['iso2']} +{number}")
            codes[number] = patterns
    if not by_iso:
        raise ValueError("The snapshot has no countries.")

    result = {}
    for country in package_countries:
        iso, number = country["iso2_cc"], country["e164_cc"]
        codes = by_iso.get(iso)
        if not codes:
            continue
        if number in codes:
            patterns = codes[number]
        elif number == "1" and all(re.fullmatch(r"1[0-9]{3}", code) for code in codes):
            # The field includes the area code when the package displays +1.
            projected = [
                ["XXX " + pattern for pattern in templates]
                for templates in codes.values()
            ]
            if any(templates != projected[0] for templates in projected[1:]):
                raise ValueError(f"Review differing NANP templates for {iso}.")
            patterns = projected[0]
        else:
            raise ValueError(f"Review the source code mapping for {iso} +{number}.")
        result[country["e164_key"]] = patterns
    return result


def render(snapshot, patterns):
    date = datetime.fromisoformat(snapshot["captured_at"]).date()
    lang = snapshot["request"]["lang_code"]
    if not re.fullmatch(r"[a-zA-Z0-9_-]+", lang):
        raise ValueError("Invalid snapshot language.")
    server_hash = int(snapshot["response"]["hash"])
    lines = [
        "// Generated by tool/python/update_phone_display_patterns.py. Do not edit by hand.",
        f"// Display patterns from Telegram help.getCountriesList, captured on {date}.",
        f"// Server hash ({lang}): {server_hash}.",
        "// Source: https://core.telegram.org/method/help.getCountriesList",
        "",
        "import 'package:meta/meta.dart';",
        "",
        "/// Display templates in source order, keyed by the bundled country e164 key.",
        "/// An empty list means the source explicitly has no display template.",
        "@internal",
        "const countryPhoneDisplayPatterns = <String, List<String>>{",
    ]
    for key, templates in sorted(patterns.items()):
        values = ", ".join(f"'{template}'" for template in templates)
        lines.append(f"  '{key}': <String>[{values}],")
    return "\n".join([*lines, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", required=True, type=Path, help="Path to the response JSON")
    parser.add_argument("--refresh", action="store_true", help="Fetch with MTProto before comparing")
    parser.add_argument("--lang", default="en", help="Language used when refreshing")
    parser.add_argument("--write", action="store_true", help="Write the Dart table after printing its diff")
    args = parser.parse_args()

    try:
        previous = (
            json.loads(args.snapshot.read_text(encoding="utf-8"))
            if args.snapshot.is_file()
            else None
        )
        if args.refresh:
            if previous and previous["request"]["lang_code"] != args.lang:
                raise ValueError("Use the existing snapshot language or choose a new path.")
            snapshot = asyncio.run(fetch(previous, args.lang))
        elif previous is None:
            raise ValueError("Provide an existing snapshot or use --refresh.")
        else:
            snapshot = previous

        countries = json.loads(COUNTRIES.read_text(encoding="utf-8"))
        generated = render(snapshot, display_patterns(snapshot, countries))
        if args.refresh and snapshot is not previous:
            args.snapshot.write_text(
                json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if generated == current:
            print(f"{OUTPUT.relative_to(ROOT)} matches the snapshot.")
            return 0

        name = OUTPUT.relative_to(ROOT).as_posix()
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=f"a/{name}",
                tofile=f"b/{name}",
            )
        )
        if args.write:
            OUTPUT.write_text(generated, encoding="utf-8")
            return 0
        return 1
    except (KeyError, OSError, TypeError, ValueError, TimeoutError) as error:
        print(f"Phone display templates: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
